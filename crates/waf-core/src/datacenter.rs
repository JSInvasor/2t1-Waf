static NETS: Lazy<Vec<IpNet>> = Lazy::new(|| {
    RAW.iter().filter_map(|s| IpNet::from_str(s).ok()).collect()
});

pub fn is_datacenter(ip: IpAddr) -> bool {
    NETS.iter().any(|n| n.contains(&ip))
}

pub fn prefix_count() -> usize { NETS.len() }

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn known_provider_ranges_match() {
        assert!(is_datacenter("5.9.42.1".parse().unwrap()),  "Hetzner");
        assert!(is_datacenter("104.131.42.1".parse().unwrap()), "DigitalOcean");
        assert!(is_datacenter("139.144.5.6".parse().unwrap()), "Linode");
        assert!(!is_datacenter("8.8.8.8".parse().unwrap()), "Google DNS public");
    }
}
